// Generated evidence is conservative: source reachability is not workflow/device qualification.
import { readFile, writeFile, readdir } from 'node:fs/promises';
const root = '.ai/reports/redesign';
const routes = JSON.parse(await readFile(`${root}/routes.json`, 'utf8'));
const components = JSON.parse(await readFile(`${root}/components.json`, 'utf8'));
const browser = JSON.parse(
  await readFile(`${root}/phase-9-validation/verified/browser-results.json`, 'utf8'),
);
const esc = (value) =>
  String(value ?? '')
    .replaceAll('|', '/')
    .replaceAll('\n', ' ');
const link = (path) => `[${path}](../../../${path})`;
const lines = [
  '# Redesign completion matrix',
  '',
  '**Release status: NOT QUALIFIED.** This matrix is generated from the live route inventory, not a manually selected page list. Partial means browser/source evidence exists but a state, subview, real API interaction, visual approval or device gate remains open. No route is marked complete solely because its code builds.',
  '',
  'Current results, blockers, platform status and changed files: [Phase 10 report](phase-10.md). Component details: [component report](component-completion.md). CI remains a [proposal](ci-proposal.md).',
  '',
  '| Route / actual page | Visual redesign | Shared components (source closure) | Responsive | Loading / empty | Error / permission | Accessibility | Functional regression | Visual regression | Remaining issues |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
];
const output = [];
for (const route of routes) {
  const captures = browser.results.filter(
    (row) => row.path === route.path && row.status === 'captured',
  );
  const heading = captures.find((row) => row.headings?.length)?.headings.join('; ') ?? route.title;
  const shared = route.shared ?? [];
  const scenarios = [...new Set(captures.map((row) => row.scenario).filter(Boolean))];
  const audit = captures.filter((row) => row.accessibility);
  const row = {
    route: route.path,
    actualPage: heading,
    sources: route.sources,
    visualRedesign: 'Partial',
    sharedComponents: shared,
    responsive: captures.length
      ? 'Browser captures; see route evidence. Native/device pending.'
      : 'Native-only or uncaptured; device pending.',
    loadingEmpty: scenarios.includes('empty')
      ? 'Empty/slow scenario captures; workflow states not exhaustive.'
      : 'Shared primitives/source reviewed; per-route state coverage partial.',
    errorPermission: scenarios.includes('denied')
      ? 'Denied/error/offline scenario captures.'
      : 'Aggregate auth/role tests; per-route denied-state coverage partial.',
    accessibility: audit.length
      ? `${audit.length} axe captures, ${audit.reduce((n, r) => n + r.accessibility.length, 0)} violations; screen readers pending.`
      : 'Shared primitive tests/source only; route screen reader unverified.',
    functionalRegression:
      'See exact unit/API/browser results; no claim of per-route real-device E2E.',
    visualRegression:
      'Phase 1/9 capture evidence; selected Phase 10 snapshots only. Approval pending.',
    remaining: 'Subview/state review and physical-device gates remain open.',
  };
  output.push(row);
  lines.push(
    `| ${esc(route.path)} — ${esc(heading)}; ${(route.sources ?? []).map(link).join(', ')} | Partial | ${shared.slice(0, 3).map(link).join(', ')}${shared.length > 3 ? `; ${shared.length} total in JSON` : ''} | ${row.responsive} | ${row.loadingEmpty} | ${row.errorPermission} | ${row.accessibility} | ${row.functionalRegression} | ${row.visualRegression} | ${row.remaining} |`,
  );
}
lines.push(
  '',
  `Registry total: **${routes.length} routes**. Generated JSON retains every source/shared-component reference. Historical inventory status strings are not reused as completion evidence.`,
  '',
  '## Subviews and remaining review',
  '',
  'Static tab/drawer/form declarations are inventoried in `phase-10-validation/subviews.json`, with source lines. Dynamic labels, permission-dependent branches and native panels still require semantic review. This inventory prevents omission; it does not certify all branches. Product tabs (stock/pricing/history/channels), online settings, POS payment review, transaction details and policy/permission forms must retain their individual checks.',
  '',
  '## Handover sources',
  '',
  '- Tokens: `packages/design-tokens/tokens.css`; declaration/line inventory in `phase-10-validation/tokens.json`. Native values are generated by the existing build.',
  '- Preference schema/defaults/resolver: `packages/contracts/src/settings.ts`; web adapter `apps/web/src/theme/Appearance.tsx`, native adapter `apps/mobile/src/theme.tsx`. Existing choice/policy semantics are documented in `docs/design-system.md`.',
  '- Final architecture, accepted decisions, security/offline boundaries and qualification rules remain in the four canonical guides, not this generated matrix.',
  '- Technical debt and release blockers remain explicitly listed in Phase 10. Windows/native devices, screen readers, peripherals and full installed-app behavior are not inferred from browser screenshots.',
);
await writeFile(`${root}/completion.md`, lines.join('\n') + '\n');
await writeFile(
  `${root}/phase-10-validation/completion.json`,
  JSON.stringify(output, null, 2) + '\n',
);
const componentLines = [
  '# Component-level completion evidence',
  '',
  'Generated from the existing component inventory. Every component remains **Partial qualification**: source/shared design audit and aggregate tests do not establish exhaustive interaction, state, screenshot or device coverage. Existing primitives/showcase remain the API reference.',
  '',
  '| Source | Exports | Platform | Kind | Size / review | Status |',
  '| --- | --- | --- | --- | --- | --- |',
];
for (const component of components)
  componentLines.push(
    `| ${link(component.path)} | ${esc(component.names?.join(', '))} | ${esc(component.platform)} | ${esc(component.kind)} | ${component.size} lines${component.size > 200 ? '; cohesion review' : ''} | Partial qualification |`,
  );
await writeFile(`${root}/component-completion.md`, componentLines.join('\n') + '\n');
async function files(dir) {
  return (
    await Promise.all(
      (await readdir(dir, { withFileTypes: true })).map((entry) =>
        entry.isDirectory() ? files(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`],
      ),
    )
  ).flat();
}
const subviews = [];
for (const path of [...(await files('apps/web/src')), ...(await files('apps/mobile/src'))].filter(
  (p) => p.endsWith('.tsx') && !p.includes('.test.'),
)) {
  (await readFile(path, 'utf8')).split('\n').forEach((line, index) => {
    if (
      /<(Tabs\.Trigger|Tabs\.Content|FormSheet|SidePanel|ConfirmDialog|CommandForm|AccordionSection)\b/.test(
        line,
      )
    )
      subviews.push({
        path,
        line: index + 1,
        declaration: line.trim(),
        review: 'Source inventoried; dynamic states/device verification partial',
      });
  });
}
await writeFile(
  `${root}/phase-10-validation/subviews.json`,
  JSON.stringify(subviews, null, 2) + '\n',
);
const tokens = [];
(await readFile('packages/design-tokens/tokens.css', 'utf8')).split('\n').forEach((line, index) => {
  const match = /^\s*(--[\w-]+):\s*(.+);/.exec(line);
  if (match) tokens.push({ name: match[1], value: match[2], line: index + 1 });
});
await writeFile(`${root}/phase-10-validation/tokens.json`, JSON.stringify(tokens, null, 2) + '\n');
console.log(
  JSON.stringify({
    routes: routes.length,
    components: components.length,
    subviews: subviews.length,
    tokens: tokens.length,
  }),
);
