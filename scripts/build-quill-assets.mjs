import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../apps/mobile/package.json', import.meta.url));
const directory = new URL('../apps/mobile/src/generated/', import.meta.url);
await mkdir(directory, { recursive: true });
const script = await readFile(require.resolve('quill/dist/quill.js'), 'utf8');
const style = await readFile(require.resolve('quill/dist/quill.snow.css'), 'utf8');
await writeFile(
  new URL('quill-assets.ts', directory),
  `// Generated by scripts/build-quill-assets.mjs. Do not edit.\nexport const quillScript = ${JSON.stringify(script)};\nexport const quillStyle = ${JSON.stringify(style)};\n`,
);
